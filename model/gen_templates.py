"""Generates rtl/shape_templates.vh from the bit-exact reference model."""
import os
from hw_model import TEMPL, TRI_TH, QUAD_TH, REJ_TH, REJECT_SCORE, CLASSES
out=os.path.join(os.path.dirname(__file__),'..','rtl','shape_templates.vh')
L=[]
L.append('// ============================================================================')
L.append('// shape_templates.vh  -  AUTO-GENERATED by model/gen_templates.py, do not edit')
L.append('// ----------------------------------------------------------------------------')
L.append('// Round-family reference templates (rasterised ideal shapes at several')
L.append('// rotations) and the moment-invariant decision thresholds (Q32).')
L.append('// ============================================================================')
L.append('localparam [3:0]  N_TMPL       = 4\'d%d;'%len(TEMPL))
L.append('localparam [40:0] TRI_TH       = 41\'d%d;   // I1 > 0.0081 -> triangle'%TRI_TH)
L.append('localparam [40:0] QUAD_TH      = 41\'d%d;   // I1 > 0.0067 -> quadrilateral'%QUAD_TH)
L.append('localparam [40:0] REJ_TH       = 41\'d%d;   // I1 > 0.0105 -> unknown'%REJ_TH)
L.append('localparam [31:0] REJECT_SCORE = 32\'d%d;'%REJECT_SCORE)
L.append('')
L.append('function [7:0] tmpl_feat;   // template t, feature i (0-6 rows, 7-13 columns)')
L.append('    input [3:0] t;\n    input [3:0] i;\n    begin\n        case ({t, i})')
for t,(c,f,i1) in enumerate(TEMPL):
    for i,v in enumerate(f):
        L.append("            8'h%X%X: tmpl_feat = 8'd%d;"%(t,i,v))
L.append("            default: tmpl_feat = 8'd0;\n        endcase\n    end\nendfunction\n")
L.append('function [40:0] tmpl_i1;     // moment invariant of template t (Q32)')
L.append('    input [3:0] t;\n    begin\n        case (t)')
for t,(c,f,i1) in enumerate(TEMPL):
    L.append("            4'd%d: tmpl_i1 = 41'd%d;   // %s"%(t,i1,CLASSES[c]))
L.append("            default: tmpl_i1 = 41'd0;\n        endcase\n    end\nendfunction\n")
L.append('function [3:0] tmpl_class;   // class code of template t')
L.append('    input [3:0] t;\n    begin\n        case (t)')
for t,(c,f,i1) in enumerate(TEMPL):
    L.append("            4'd%d: tmpl_class = 4'd%d;   // %s"%(t,c,CLASSES[c]))
L.append("            default: tmpl_class = 4'd8;\n        endcase\n    end\nendfunction")
open(out,'w').write('\n'.join(L)+'\n')
print('wrote',os.path.abspath(out))
